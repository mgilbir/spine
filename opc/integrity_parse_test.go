// --- C393: content types must not be steerable from a foreign namespace ----

// TestContentTypesIgnoresForeignNamespace is the regression test for C393.
// UnmarshalContentTypes dispatched on the local name alone, so an
// <evil:Override> — an element every conformant consumer ignores — set the
// content type that drives every downstream part-kind decision.
func TestContentTypesIgnoresForeignNamespace(t *testing.T) {
	src := `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` + "\r\n" +
		`<Types xmlns="` + ContentTypesNamespace + `" xmlns:evil="urn:evil">` +
		`<Default Extension="xml" ContentType="application/xml"/>` +
		`<evil:Override PartName="/word/document.xml" ContentType="application/evil"/>` +
		`<evil:Default Extension="png" ContentType="application/evil"/>` +
		`</Types>`

	ct, err := UnmarshalContentTypes([]byte(src))
	if err != nil {
		t.Fatalf("UnmarshalContentTypes() error = %v", err)
	}
	if got := ct.GetContentType("/word/document.xml"); got == "application/evil" {
		t.Errorf("GetContentType(/word/document.xml) = %q; a foreign-namespace Override must not steer the part kind (C393)", got)
	}
	if got := ct.GetContentType("/word/document.xml"); got != "application/xml" {
		t.Errorf("GetContentType(/word/document.xml) = %q, want the Default mapping %q", got, "application/xml")
	}
	if got := ct.GetContentType("/ppt/media/i.png"); got == "application/evil" {
		t.Errorf("a foreign-namespace Default was honoured: %q", got)
	}
	if _, ok := ct.Overrides["/word/document.xml"]; ok {
		t.Error("a foreign-namespace Override entered Overrides")
	}

	// The foreign markup must survive regeneration rather than be dropped.
	out, err := ct.Marshal()
	if err != nil {
		t.Fatalf("Marshal() error = %v", err)
	}
	if !bytes.Equal(out, []byte(src)) {
		t.Errorf("round-trip is not byte-identical:\n got %s\nwant %s", out, src)
	}
}

// TestContentTypesAcceptsLegacyNamespaceless keeps the tolerance the parser has
// always had: files with no namespace declaration at all still parse. Real
// producers are sloppy and C393 must reject the hostile case only.
func TestContentTypesAcceptsLegacyNamespaceless(t *testing.T) {
	src := `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` + "\r\n" +
		`<Types><Default Extension="xml" ContentType="application/xml"/>` +
		`<Override PartName="/word/document.xml" ContentType="` + ContentTypeDocument + `"/></Types>`

	ct, err := UnmarshalContentTypes([]byte(src))
	if err != nil {
		t.Fatalf("UnmarshalContentTypes() error = %v", err)
	}
	if got := ct.GetContentType("/word/document.xml"); got != ContentTypeDocument {
		t.Errorf("GetContentType() = %q, want %q for a namespace-less legacy file", got, ContentTypeDocument)
	}
}

