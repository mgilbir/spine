// --- C455: nil-receiver symmetry -------------------------------------------

// TestCustomPropertiesNilReceiver is the regression test for C455: Set and
// Marshal panicked on the nil receiver that Reader.CustomProperties is
// documented to be when a package has none, while eight sibling methods
// nil-guarded.
func TestCustomPropertiesNilReceiver(t *testing.T) {
	var cp *CustomProperties

	err := cp.Set("k", "v")
	if err == nil {
		t.Error("Set on a nil receiver returned no error")
	} else if !strings.Contains(err.Error(), "nil") {
		t.Errorf("Set error = %v, want it to name the nil receiver", err)
	}

	data, err := cp.Marshal()
	if err != nil {
		t.Fatalf("Marshal on a nil receiver error = %v", err)
	}
	got, err := UnmarshalCustomProperties(data)
	if err != nil {
		t.Fatalf("the nil receiver's Marshal output does not parse: %v\n%s", err, data)
	}
	if got.Len() != 0 {
		t.Errorf("nil receiver marshalled %d properties, want 0", got.Len())
	}

	// The documented fix works.
	cp = &CustomProperties{}
	if err := cp.Set("k", "v"); err != nil {
		t.Errorf("Set on a fresh &CustomProperties{} error = %v", err)
	}
}
