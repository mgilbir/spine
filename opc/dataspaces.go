package opc

// This file provides the optional \x06DataSpaces metadata streams that Office
// writes alongside EncryptionInfo/EncryptedPackage in an encrypted document
// ([MS-OFFCRYPTO] §2.1). They are not needed to decrypt the package — this
// library and reference tools ignore them on read — but some Office builds
// expect them, so encrypted saves can opt in via EncryptOptions.IncludeDataSpaces.
//
// The stream payloads below are the fixed, canonical byte templates used by
// Microsoft's own and reference implementations (the Herumi/msoffice C++
// resources, mirrored by msoffcrypto-tool) for password-encrypted packages: a
// single StrongEncryptionTransform mapping the EncryptedPackage stream through
// the StrongEncryptionDataSpace. They are stored verbatim to avoid any
// divergence from what Office accepts.

// DataSpaces stream/storage names inside the container ([MS-OFFCRYPTO] §2.1.1).
const (
	dsStorageRoot          = "\x06DataSpaces"
	dsStreamVersion        = "Version"
	dsStreamDataSpaceMap   = "DataSpaceMap"
	dsStorageDataSpaceInfo = "DataSpaceInfo"
	dsStreamStrongDS       = "StrongEncryptionDataSpace"
	dsStorageTransformInfo = "TransformInfo"
	dsStorageStrongXform   = "StrongEncryptionTransform"
	dsStreamPrimary        = "\x06Primary"
)

// dsVersionContent is the \x06DataSpaces/Version stream: a DataSpaceVersionInfo
// naming "Microsoft.Container.DataSpaces" with reader/updater/writer 1.0.
var dsVersionContent = []byte{
	0x3c, 0x00, 0x00, 0x00, // length-prefix: 0x3c bytes of UTF-16LE
	0x4d, 0x00, 0x69, 0x00, 0x63, 0x00, 0x72, 0x00, 0x6f, 0x00, 0x73, 0x00,
	0x6f, 0x00, 0x66, 0x00, 0x74, 0x00, 0x2e, 0x00, 0x43, 0x00, 0x6f, 0x00,
	0x6e, 0x00, 0x74, 0x00, 0x61, 0x00, 0x69, 0x00, 0x6e, 0x00, 0x65, 0x00,
	0x72, 0x00, 0x2e, 0x00, 0x44, 0x00, 0x61, 0x00, 0x74, 0x00, 0x61, 0x00,
	0x53, 0x00, 0x70, 0x00, 0x61, 0x00, 0x63, 0x00, 0x65, 0x00, 0x73, 0x00,
	0x01, 0x00, 0x00, 0x00, // ReaderVersion 1.0
	0x01, 0x00, 0x00, 0x00, // UpdaterVersion 1.0
	0x01, 0x00, 0x00, 0x00, // WriterVersion 1.0
}

// dsDataSpaceMapContent is the \x06DataSpaces/DataSpaceMap stream: one entry
