// dataSpacesStorages returns the \x06DataSpaces storage subtree to embed in an
// encrypted container.
func dataSpacesStorages() []cfbStorage {
	return []cfbStorage{{
		name: dsStorageRoot,
		streams: []cfbStream{
			{name: dsStreamVersion, data: dsVersionContent},
			{name: dsStreamDataSpaceMap, data: dsDataSpaceMapContent},
		},
		storages: []cfbStorage{
			{
				name:    dsStorageDataSpaceInfo,
				streams: []cfbStream{{name: dsStreamStrongDS, data: dsStrongDSContent}},
			},
			{
				name: dsStorageTransformInfo,
				storages: []cfbStorage{{
					name:    dsStorageStrongXform,
					streams: []cfbStream{{name: dsStreamPrimary, data: dsPrimaryContent}},
				}},
			},
		},
	}}
}
