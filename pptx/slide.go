// tableDataToOxml converts Table data to oxml.ATable.
func tableDataToOxml(t *Table) *oxml.ATable {
	tbl := &oxml.ATable{
		TblPr: &oxml.ATblPr{
			FirstRow:     t.firstRow,
			FirstCol:     t.firstCol,
			LastRow:      t.lastRow,
			LastCol:      t.lastCol,
			BandRow:      t.bandRow,
			BandCol:      t.bandCol,
			TableStyleId: t.tableStyleID,
		},
		TblGrid: &oxml.ATblGrid{
			GridCol: make([]*oxml.AGridCol, len(t.colWidths)),
		},
		Tr: make([]*oxml.ATr, len(t.rows)),
	}

	// Set column widths
	for i, w := range t.colWidths {
		tbl.TblGrid.GridCol[i] = &oxml.AGridCol{W: int64(w)}
	}

	// Convert rows
	for i, row := range t.rows {
		rowH := int64(row.height)
		tr := &oxml.ATr{
			H:  &rowH,
			Tc: make([]*oxml.ATc, len(row.cells)),
		}

		for j, cell := range row.cells {
			tc := &oxml.ATc{}

			// Set cell properties
			if cell.fill != nil || cell.vertAlign != "" ||
				cell.borderLeft != nil || cell.borderRight != nil ||
				cell.borderTop != nil || cell.borderBottom != nil ||
				cell.margins != nil {
				tc.TcPr = &oxml.ATcPr{}
				if cell.vertAlign != "" {
					tc.TcPr.Anchor = string(cell.vertAlign)
				}
				applyCellMargins(tc.TcPr, cell)
				tc.TcPr.LnL = tableBorderToLn(cell.borderLeft)
				tc.TcPr.LnR = tableBorderToLn(cell.borderRight)
				tc.TcPr.LnT = tableBorderToLn(cell.borderTop)
				tc.TcPr.LnB = tableBorderToLn(cell.borderBottom)
				if cell.fill != nil {
					tc.TcPr.SolidFill = colorToOxml(cell.fill)
				}
			}

			// Set row/col span
			if cell.rowSpan > 1 {
				tc.RowSpan = cell.rowSpan
			}
			if cell.colSpan > 1 {
				tc.GridSpan = cell.colSpan
			}
			tc.HMerge = cell.hMerge
			tc.VMerge = cell.vMerge

			// Convert text
			if cell.textFrame != nil {
				tc.TxBody = textFrameToOxml(cell.textFrame)
			}

			tr.Tc[j] = tc
			cell.sourceTc = tc
		}

		tbl.Tr[i] = tr
		row.sourceTr = tr
	}

	return tbl
}

// regenerateTableNode rebuilds the a:tbl from the domain model after a
// structural change (rows/columns added or removed), carrying parsed content
// over for surviving rows and cells: their tcPr (margins, borders, fills the
// domain does not track per edge) and, when the cell text was not edited,
// their txBody are reused verbatim, and the table keeps its tableStyleId.
// Cells the caller explicitly restyled get those edits applied on top of the
// parsed properties.
func regenerateTableNode(t *Table, old *oxml.ATable) *oxml.ATable {
	// Capture the parsed source nodes before tableDataToOxml re-points every
	// row/cell at its freshly built node.
	oldTr := make([]*oxml.ATr, len(t.rows))
	oldTc := make([][]*oxml.ATc, len(t.rows))
	for i, row := range t.rows {
		oldTr[i] = row.sourceTr
		oldTc[i] = make([]*oxml.ATc, len(row.cells))
		for j, c := range row.cells {
			oldTc[i][j] = c.sourceTc
		}
	}

	tbl := tableDataToOxml(t)
	// tbl.TblPr.TableStyleId already reflects t.tableStyleID, which was
	// materialized from the source table (or overridden via SetStyleID), so the
	// style reference is carried over without re-reading the old node.
	if old != nil && old.TblGrid != nil && tbl.TblGrid != nil &&
		len(old.TblGrid.GridCol) == len(tbl.TblGrid.GridCol) {
		for i, gc := range tbl.TblGrid.GridCol {
			gc.ExtLst = old.TblGrid.GridCol[i].ExtLst
		}
	}

	for i, tr := range tbl.Tr {
		if src := oldTr[i]; src != nil {
			tr.ExtLst = src.ExtLst
		}
		for j, tc := range tr.Tc {
			src := oldTc[i][j]
			if src == nil {
				continue // new cell: keep the generated node
			}
			cell := t.rows[i].cells[j]
			tc.TcPr = src.TcPr
			if cell.dirty {
				applyCellProps(tc, cell)
			}
			tc.TxBody = src.TxBody
			if cell.textFrame != nil && cell.textFrame.isDirty() {
				updateTxBody(&tc.TxBody, cell.textFrame)
			}
		}
	}
	return tbl
}

// tableBorderToLn converts a domain TableBorder to a dml.Ln for a cell edge.
func tableBorderToLn(b *TableBorder) *dml.Ln {
	if b == nil {
		return nil
	}
	ln := &dml.Ln{}
	if b.Width > 0 {
		w := int64(b.Width)
		ln.W = &w
	}
	switch b.Style {
	case BorderStyleNone:
		// An explicit "no border" — emit a line with no fill.
		ln.NoFill = &dml.NoFillXML{}
		return ln
	case BorderStyleDashed:
		ln.PrstDash = &dml.PrstDash{Val: "dash"}
	case BorderStyleDotted:
		ln.PrstDash = &dml.PrstDash{Val: "dot"}
	case BorderStyleDouble:
		ln.Cmpd = "dbl"
	}
	ln.SolidFill = colorToOxml(&b.Color)
	return ln
}

// pictureToOxml converts a Picture to oxml.Picture.
func pictureToOxml(p *Picture, id uint32) *oxml.Picture {
	name := p.Name()
	if name == "" {
		name = "Picture"
	}

	x, y := p.Position()
	w, h := p.Size()

	pic := &oxml.Picture{
		NvPicPr: &oxml.NvPicPr{
			CNvPr: &dml.CNvPr{
				Id:    id,
				Name:  name,
				Descr: p.description,
			},
			CNvPicPr: &dml.CNvPicPr{
				PicLocks: &dml.PicLocks{NoChangeAspect: true},
			},
			NvPr: &oxml.NvPr{},
		},
		BlipFill: &dml.BlipFill{
			Blip: &dml.Blip{
				// The embed reference will be set when saving with relationships
				Embed: p.relID,
			},
			Stretch: &dml.Stretch{
				FillRect: &dml.RelRect{},
			},
		},
		SpPr: &dml.SpPr{
			Xfrm: &dml.Xfrm{
				Off: &dml.OffXML{X: int64(x), Y: int64(y)},
				Ext: &dml.ExtXML{Cx: int64(w), Cy: int64(h)},
			},
			PrstGeom: &dml.PrstGeom{
				Prst:  "rect",
				AvLst: &dml.AvLst{},
			},
		},
	}

	if p.hyperlink != nil {
		pic.NvPicPr.CNvPr.HlinkClick = hyperlinkToXML(p.hyperlink)
	}

	// Apply cropping if set
	if p.cropLeft > 0 || p.cropTop > 0 || p.cropRight > 0 || p.cropBottom > 0 {
		pic.BlipFill.SrcRect = &dml.SrcRect{
			L: dml.NewPercentage(int32(p.cropLeft * 100000)),
			T: dml.NewPercentage(int32(p.cropTop * 100000)),
			R: dml.NewPercentage(int32(p.cropRight * 100000)),
			B: dml.NewPercentage(int32(p.cropBottom * 100000)),
		}
	}

	return pic
}

// Duplicate creates a copy of the slide and adds it after this slide.
func (s *Slide) Duplicate() *Slide {
	if s.shapesModified || s.hasDirtyShapes() {
		s.syncShapesToXML()
	}
	// Build any pending auto-play timing tree now, before the XML snapshot
	// below: timing is normally built at save, so duplicating an unsaved
	// slide with auto-play media would otherwise snapshot a tree-less slide
	// and the duplicate would silently lose autoplay (C193). The copied tree
	// targets the same shape ids the copied shapes carry, so it is valid for
	// the duplicate as-is.
	s.applyMediaTiming()
	s.applyAnimations()

	// AddSlide assigned the duplicate its own part name.
	newSlide := s.presentation.AddSlide()
	newSlide.layout = s.layout

	// Copy slide XML and slide-level relationships so the duplicate remains self-contained.
	if s.slideXML != nil {
		if data, err := marshalSlide(s.slideXML); err == nil {
			var copyXML oxml.Slide
			if err := xml.Unmarshal(data, &copyXML); err == nil {
				newSlide.slideXML = &copyXML
			}
		}
	}
	if s.partName != "" {
		s.presentation.clonePartRelationships(s.partName, newSlide.partName)
		// Give the duplicate its own notes slide rather than sharing the
		// original's (otherwise editing one slide's notes changes the other).
		s.presentation.deepCloneNotesSlide(newSlide.partName)
	}
	if newSlide.slideXML == nil {
		newSlide.slideXML = newSlideXML()
	}
	newSlide.materializeShapes()

	// Move to position after original
	_ = s.presentation.MoveSlide(newSlide.index, s.index+1)

	return newSlide
}

// Delete removes this slide from the presentation.
func (s *Slide) Delete() error {
	return s.presentation.RemoveSlide(s.index)
}
