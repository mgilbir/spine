// textFrameToOxml converts a TextFrame to dml.TxBody.
func textFrameToOxml(tf *TextFrame) *dml.TxBody {
	lIns := int64(tf.margins.Left)
	tIns := int64(tf.margins.Top)
	rIns := int64(tf.margins.Right)
	bIns := int64(tf.margins.Bottom)
	txBody := &dml.TxBody{
		BodyPr: &dml.BodyPr{
			Wrap:   string(tf.wrap),
			Anchor: string(tf.anchor),
			LIns:   &lIns,
			TIns:   &tIns,
			RIns:   &rIns,
			BIns:   &bIns,
		},
		LstStyle: &dml.LstStyle{},
		P:        make([]*dml.P, 0, len(tf.paragraphs)),
	}
	applyAutofit(txBody.BodyPr, tf.autofit)

	for _, para := range tf.paragraphs {
		ap := paragraphToOxml(para)
		txBody.P = append(txBody.P, ap)
	}

	// Ensure at least one paragraph
	if len(txBody.P) == 0 {
		txBody.P = append(txBody.P, &dml.P{})
	}

	return txBody
}

// paragraphToOxml converts a Paragraph to dml.P.
func paragraphToOxml(p *Paragraph) *dml.P {
	ap := &dml.P{
		R: make([]*dml.R, 0, len(p.runs)),
	}

	// Set paragraph properties if needed. An explicitly-set zero counts: the
	// caller asking for "no space before" must reach the XML, since omitting the
	// element means "inherit" (C518).
	needSpacing := p.lineSpacing != 0 || p.spaceBefore != 0 || p.spaceAfter != 0 ||
		p.isSet(paraPropSpaceBefore|paraPropSpaceAfter)
	needBulletStyle := p.bulletColor != nil || p.bulletSizePct != 0 || p.bulletFont != ""
	needIndent := p.marL != nil || p.indent != nil || len(p.tabStops) > 0
	if p.alignment != "" || p.level > 0 || p.isSet(paraPropLevel) ||
		p.bulletType != BulletInherit || needSpacing || needBulletStyle || needIndent {
		ap.PPr = &dml.PPr{
			MarL:   p.marL,
			Indent: p.indent,
			Algn:   string(p.alignment),
		}

		// Emit lvl only when the paragraph is actually at a nonzero level or the
		// caller set one explicitly. Emitting lvl="0" unconditionally put an
		// attribute on every regenerated paragraph that the source never carried
		// (C517).
		if p.level > 0 || p.isSet(paraPropLevel) {
			lvl := int32(p.level)
			ap.PPr.Lvl = &lvl
		}

		// Bullet styling (color/size/font) applies to whichever bullet kind the
		// paragraph carries, so it is emitted independently of the bullet type.
		if p.bulletColor != nil {
			ap.PPr.BuClr = colorToBuClr(p.bulletColor)
		}
		if p.bulletSizePct != 0 {
			ap.PPr.BuSzPct = &dml.BuSzPct{Val: dml.NewPercentage(p.bulletSizePct)}
		}
		if p.bulletFont != "" {
			ap.PPr.BuFont = &dml.BuFont{Typeface: p.bulletFont}
		}

		// Emit a bullet element only when the bullet was set explicitly.
		// BulletInherit (the default) emits nothing so the paragraph keeps the
		// layout/master bullet even when other properties (alignment, spacing)
		// are set.
		applyBulletKind(ap.PPr, p)

		ap.PPr.TabLst = tabStopsToOxml(p.tabStops)

		// Spacing (symmetric with the oxml->domain read): line spacing is a
		// percentage, space before/after are point values. An explicit zero set
		// through the setter is emitted rather than suppressed, so "no space
		// before this paragraph" is expressible and does not silently inherit
		// (C518); line spacing keeps its documented 0 == inherit meaning.
		if p.lineSpacing != 0 {
			ap.PPr.LnSpc = &dml.LnSpc{SpcPct: &dml.SpcPct{Val: dml.NewPercentage(p.lineSpacing)}}
		}
		if p.spaceBefore != 0 || p.isSet(paraPropSpaceBefore) {
			ap.PPr.SpcBef = &dml.SpcBef{SpcPts: &dml.SpcPts{Val: int32(p.spaceBefore)}}
		}
		if p.spaceAfter != 0 || p.isSet(paraPropSpaceAfter) {
			ap.PPr.SpcAft = &dml.SpcAft{SpcPts: &dml.SpcPts{Val: int32(p.spaceAfter)}}
		}
	}

	// Convert runs
	for _, run := range p.runs {
		ar := runToOxml(run)
		ap.R = append(ap.R, ar)
	}

	return ap
}

// runToOxml converts a Run to dml.R.
func runToOxml(r *Run) *dml.R {
	ar := &dml.R{
		T: r.text,
	}

	// Set run properties if any formatting is applied. An explicitly-set false
	// counts: omitting b/i means "inherit", so a run the caller un-bolded must
	// still emit b="0" or it re-inherits bold from its placeholder (C518).
	if r.fontName != "" || r.fontSize > 0 || r.bold || r.italic ||
		r.underline != "" || r.strike != "" || r.color != nil || r.baseline != 0 ||
		r.highlight != nil || r.isSet(runPropBold|runPropItalic) {
		ar.RPr = &dml.RPr{}

		if r.highlight != nil {
			ar.RPr.Highlight = colorToColorChoiceOxml(r.highlight)
		}

		if r.fontSize > 0 {
			ar.RPr.Sz = int32(r.fontSize * 100) // Convert points to hundredths
		}

		if r.bold || r.isSet(runPropBold) {
			b := r.bold
			ar.RPr.B = &b
		}

		if r.italic || r.isSet(runPropItalic) {
			i := r.italic
			ar.RPr.I = &i
		}

		if r.underline != "" {
			ar.RPr.U = string(r.underline)
		}

		if r.strike != "" {
			ar.RPr.Strike = string(r.strike)
		}

		if r.baseline != 0 {
			baseline := dml.NewPercentage(r.baseline)
			ar.RPr.Baseline = &baseline
		}

		if r.fontName != "" {
			ar.RPr.Latin = &dml.TextFont{Typeface: r.fontName}
		}

		if r.color != nil {
			ar.RPr.SolidFill = colorToOxml(r.color)
		}
	}

	// A hyperlink lives in a:hlinkClick on the run properties, so it needs an
	// rPr even when no other formatting is set.
	if r.hyperlink != nil {
		if ar.RPr == nil {
			ar.RPr = &dml.RPr{}
		}
		ar.RPr.HlinkClick = hyperlinkToXML(r.hyperlink)
	}

	return ar
}

// applyAutofit sets the body's autofit child to match the domain mode, clearing
// the others first. AutofitInherit leaves all three unset so the body inherits.
func applyAutofit(bp *dml.BodyPr, autofit AutofitType) {
	bp.NoAutofit, bp.NormAutofit, bp.SpAutoFit = nil, nil, nil
	switch autofit {
	case AutofitNone:
		bp.NoAutofit = &dml.NoAutofit{}
	case AutofitShape:
		bp.SpAutoFit = &dml.SpAutoFit{}
	case AutofitNormal:
		bp.NormAutofit = &dml.NormAutofit{}
	}
}

// colorToBuClr converts a Color to a dml.BuClr (a:buClr bullet color).
func colorToBuClr(c *dml.Color) *dml.BuClr {
	if c == nil {
		return nil
	}
	bc := &dml.BuClr{}
	if c.Type == dml.ColorTypeTheme {
		bc.SchemeClr = &dml.SchemeClrTransform{Val: c.Theme.String()}
	} else {
		bc.SrgbClr = &dml.SrgbClr{Val: c.RGB.String()}
	}
	return bc
}

// buClrToColor converts a dml.BuClr bullet color to a dml.Color.
func buClrToColor(bc *dml.BuClr) *dml.Color {
	if bc == nil {
		return nil
	}
	if bc.SrgbClr != nil {
		if rgb, err := dml.ParseRGB(bc.SrgbClr.Val); err == nil {
			c := rgb.ToColor()
			return &c
		}
	}
	if bc.SchemeClr != nil {
		c := parseThemeColorString(bc.SchemeClr.Val).ToColor()
		return &c
	}
	return nil
}

