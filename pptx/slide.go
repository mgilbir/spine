// Slide represents a slide in a presentation.
type Slide struct {
	presentation *Presentation
	layout       *SlideLayout
	partName     string
	slideXML     *oxml.Slide
	index        int
	id           uint32
	relID        string
	// idExtLst preserves the extLst child of this slide's p:sldId entry in
	// presentation.xml, which is regenerated on every save (C225).
	idExtLst       *oxml.ExtensionList
	shapes         []Shape
	shapesModified bool // true if shapes changed via Go API

	// syncedShapes counts the leading shapes already represented in slideXML
	// (the parsed shapes of a loaded slide). When only appends happened,
	// marshal() syncs just the new shapes into the parsed tree instead of
	// rebuilding it — a rebuild drops slide content the domain model cannot
	// represent (group shapes, connectors) and re-numbers every shape.
	syncedShapes int
	// forceShapeRebuild is set by structural edits the surgical/append sync
	// cannot express, forcing a full rebuild from the domain model.
	forceShapeRebuild bool
	// shapeRefs records, for each materialized (parsed) shape in shapes, the
	// child reference in the parsed shape tree it came from. It stays aligned
	// with shapes[:syncedShapes] so a removed shape can be deleted surgically.
	shapeRefs []oxml.ChildRef
	// removedRefs collects the parsed child references removed via RemoveShape,
	// applied at sync time by deleting just those nodes (preserving everything
	// else, including content the domain model cannot represent).
	removedRefs []oxml.ChildRef
	// autoplayMedia records the shape ids of auto-play video/audio added to the
	// slide, collected during the shape sync and used to build the timing tree.
	autoplayMedia []mediaTimingRef
	// autoTimingRefs is the full set of auto-play refs the current generated
	// timing tree was built from. Appends accumulate into it; a full rebuild
	// (which renumbers shape ids) resets it so the tree is regenerated from
	// the fresh ids.
	autoTimingRefs []mediaTimingRef
	// timingAutoGenerated marks the slide's timing tree as one this library
	// built for auto-play media. Only such trees may be regenerated; a timing
	// tree parsed from an opened file is never touched.
	timingAutoGenerated bool
	// timingRegen is set by a full shape rebuild: ids were renumbered and
	// autoplayMedia re-collected from scratch, so any generated timing tree
	// must be rebuilt (or dropped) from that complete set.
	timingRegen bool
	// pendingAnims holds animations added via AddAnimation that have not yet
	// been serialized into the timing tree; applyAnimations flushes them at
	// save. A slide with no pending animations never has its timing touched.
	pendingAnims []*Animation
}

// Index returns the 0-based index of the slide in the presentation.
func (s *Slide) Index() int {
	return s.index
}

// RelID returns the slide's presentation-level relationship id (the r:id of its
// p:sldId entry in presentation.xml). For a slide loaded from a file this is its
// stored id; for a slide created through this package the id is assigned when
// the deck is first saved, so RelID reports an empty string until then. It is
// the identifier a custom show references (see Presentation.AddCustomShow).
func (s *Slide) RelID() string {
	return s.relID
}

// Name returns the name of the slide, if any.
func (s *Slide) Name() string {
	if s.slideXML != nil && s.slideXML.CSld != nil {
		return s.slideXML.CSld.Name
	}
	return ""
}

// SetName sets the name of the slide.
func (s *Slide) SetName(name string) {
	if s.slideXML == nil {
		s.slideXML = newSlideXML()
	}
	if s.slideXML.CSld == nil {
		s.slideXML.CSld = &oxml.CommonSlideData{}
	}
	s.slideXML.CSld.Name = name
	s.shapesModified = true
}

// Layout returns the slide layout, or nil if none is set.
func (s *Slide) Layout() *SlideLayout {
	return s.layout
}

// Shapes returns all shapes on the slide.
func (s *Slide) Shapes() []Shape {
	return s.shapes
}

// AddShape adds a shape to the slide. It returns an error for shape types the
// library cannot serialize (previously such shapes were accepted and then
// silently dropped on save). All shape types constructible through this
// package — TextBox, PlaceholderShape, AutoShape, Table, Picture, Video,
// Audio, and GroupShape — are supported.
func (s *Slide) AddShape(shape Shape) error {
	switch shape.(type) {
	case *TextBox, *PlaceholderShape, *AutoShape, *Table, *Picture, *Video, *Audio, *GroupShape, *Connector:
		s.addShape(shape)
		return nil
	default:
		return fmt.Errorf("pptx: AddShape: unsupported shape type %T", shape)
	}
}

// addShape appends a shape the sync paths know how to serialize.
func (s *Slide) addShape(shape Shape) {
	s.setShapeBackRef(shape)
	s.shapes = append(s.shapes, shape)
	s.shapesModified = true
}

// RemoveShape removes a shape from the slide. On a slide loaded from a file the
// removed shape's node is deleted surgically from the parsed tree on save, so
// other content (including group shapes, connectors, and other kinds the domain
// model does not represent) is preserved.
func (s *Slide) RemoveShape(shape Shape) {
	for i, sh := range s.shapes {
		if sh != shape {
			continue
		}
		switch {
		case i < s.syncedShapes && i < len(s.shapeRefs):
			// A synced shape: mark its source node for surgical deletion. A
			// sentinel ref (Index -1) means the shape never made it into the
			// tree, so there is nothing to delete there.
			if ref := s.shapeRefs[i]; ref.Index >= 0 {
				s.removedRefs = append(s.removedRefs, ref)
			}
			s.shapeRefs = append(s.shapeRefs[:i], s.shapeRefs[i+1:]...)
			s.syncedShapes--
		case i < s.syncedShapes:
			// Parsed shape without a tracked source (no child-order info):
			// fall back to a full rebuild.
			s.forceShapeRebuild = true
		}
		// Shapes added after the last sync were never written; dropping them
		// from the slice is sufficient.
		s.shapes = append(s.shapes[:i], s.shapes[i+1:]...)
		s.shapesModified = true
		return
	}
}

// AddTextBox adds a text box shape to the slide.
func (s *Slide) AddTextBox() *TextBox {
	tb := NewTextBox()
	s.addShape(tb)
	return tb
}

// AddPicture adds a picture shape to the slide, reading the image from
// imagePath. It returns an error if the file cannot be read (previously the
// path was stored without reading it, so a nonexistent file returned no error
// and produced a blip with no image reference). The image data is embedded as a
// media part when the presentation is saved.
//
// The picture frame defaults to the image's intrinsic size at 96 DPI (decoded
// from the PNG/JPEG/GIF header; other formats fall back to 4x3 inches), so the
// picture is visible without further setup. Call SetSize/SetPosition on the
// returned Picture to place it explicitly.
func (s *Slide) AddPicture(imagePath string) (*Picture, error) {
	pic := NewPicture()
	if err := pic.SetImage(imagePath); err != nil {
		return nil, err
	}
	if w, h, ok := nativeImageSize(pic.imageData); ok {
		pic.SetSize(w, h)
	} else {
		pic.SetSize(dml.Inches(4), dml.Inches(3))
	}
	s.addShape(pic)
	return pic, nil
}

// AddPictureFromBytes adds a picture to the slide from raw image bytes and
// their content type (e.g. "image/png"), embedding the image in the .pptx on
// save. This is the byte-slice counterpart to AddPicture (which reads a file)
// and mirrors AddVideo/AddAudio. The frame defaults to the image's intrinsic
// pixel size at 96 DPI, or 4x3 inches when the dimensions cannot be decoded;
// override it with Picture.SetSize.
//
// Saving fails with an error when the data is empty or not a decodable image.
func (s *Slide) AddPictureFromBytes(data []byte, contentType string) (*Picture, error) {
	if len(data) == 0 {
		return nil, fmt.Errorf("pptx: AddPictureFromBytes: image data is empty")
	}
	pic := NewPicture()
	pic.SetImageData(data, contentType)
	if w, h, ok := nativeImageSize(data); ok {
		pic.SetSize(w, h)
	} else {
		pic.SetSize(dml.Inches(4), dml.Inches(3))
	}
	s.addShape(pic)
	return pic, nil
}

// AddTable adds a table to the slide.
func (s *Slide) AddTable(rows, cols int) *Table {
	table := NewTable(rows, cols)
	s.addShape(table)
	return table
}

// AddConnector adds a connector (a p:cxnSp connection shape) to the slide and
// returns it for further configuration. Bind its ends to shapes with
// Connect / SetStartShape / SetEndShape (the cNvPr ids are resolved on save,
// so it can target API-created shapes) or place it freely with SetPoints, and
// style its line with SetLine / SetLineWidth / SetLineColor / SetLineDash. The
// connector participates in the shape sync, so it coexists with existing
// shapes and preserved connectors on a loaded slide.
func (s *Slide) AddConnector(kind ConnectorKind) *Connector {
	c := NewConnector(kind)
	s.addShape(c)
	return c
}

// Connectors returns the connectors (p:cxnSp) on the slide, in z-order.
func (s *Slide) Connectors() []*Connector {
	var out []*Connector
	for _, sh := range s.shapes {
		if c, ok := sh.(*Connector); ok {
			out = append(out, c)
		}
	}
	return out
}

// AddVideo embeds a video in the slide from raw media bytes and their content
// type (e.g. "video/mp4"). The video is stored inside the .pptx and plays on
// click in PowerPoint. Set a poster image with Video.SetPoster; otherwise a
// placeholder preview is generated on save. An empty contentType is inferred
// from the data's magic bytes; saving fails with an error when the data is
// empty or the content type is neither given nor recognizable.
func (s *Slide) AddVideo(data []byte, contentType string) *Video {
	v := NewVideo(data, contentType)
	s.addShape(v)
	return v
}

// AddAudio embeds an audio clip in the slide from raw media bytes and their
// content type (e.g. "audio/mpeg"). Set an icon image with Audio.SetPoster;
// otherwise a placeholder is generated on save. An empty contentType is
// inferred from the data's magic bytes; saving fails with an error when the
// data is empty or the content type is neither given nor recognizable.
func (s *Slide) AddAudio(data []byte, contentType string) *Audio {
	a := NewAudio(data, contentType)
	s.addShape(a)
	return a
}

// Placeholders returns all placeholder shapes on the slide.
func (s *Slide) Placeholders() []*PlaceholderShape {
	var placeholders []*PlaceholderShape
	for _, shape := range s.shapes {
		if ph, ok := shape.(*PlaceholderShape); ok {
			placeholders = append(placeholders, ph)
		}
	}
	return placeholders
}

// GetPlaceholder returns the placeholder with the specified type, or nil.
func (s *Slide) GetPlaceholder(phType PlaceholderType) *PlaceholderShape {
	for _, shape := range s.shapes {
		if ph, ok := shape.(*PlaceholderShape); ok {
			if ph.PlaceholderType() == phType {
				return ph
			}
		}
	}
	return nil
}

// ShapeByName returns the first shape with the given name, or nil if not found.
func (s *Slide) ShapeByName(name string) Shape {
	for _, shape := range s.shapes {
		if found := shapeByName(shape, name); found != nil {
			return found
		}
	}
	return nil
}

func shapeByName(shape Shape, name string) Shape {
	if shape.Name() == name {
		return shape
	}
	if group, ok := shape.(*GroupShape); ok {
		for _, child := range group.Children() {
			if found := shapeByName(child, name); found != nil {
				return found
			}
		}
	}
	return nil
}

// TitlePlaceholder returns the title placeholder, or nil if none exists.
func (s *Slide) TitlePlaceholder() *PlaceholderShape {
	return s.GetPlaceholder(PlaceholderTitle)
}

// BodyPlaceholder returns the body/content placeholder, or nil if none exists.
func (s *Slide) BodyPlaceholder() *PlaceholderShape {
	return s.GetPlaceholder(PlaceholderBody)
}

// marshal converts the slide to XML bytes.
func (s *Slide) marshal() ([]byte, error) {
	if s.slideXML == nil {
		s.slideXML = newSlideXML()
	}

	// Reject media that cannot become a valid package part (no data, or no
	// recognizable content type) before any of it is written.
	if err := s.validateMediaShapes(); err != nil {
		return nil, err
	}

	// Only sync Go shapes to XML when shapes were modified via the API: added
	// or removed (shapesModified), or mutated in place (dirty flags). When
	// loading from a file, the slideXML already contains the parsed shapes.
	if s.shapesModified || s.hasDirtyShapes() {
		s.syncShapesToXML()
	}

	// Process any pending image replacements after the XML tree is up to date.
	// This modifies the XML directly, converting p:sp elements to p:pic elements
	// or swapping the blip reference on existing pictures.
	if err := s.processPendingImages(); err != nil {
		return nil, err
	}

	// Build the timing tree for any auto-play media added to the slide (needs the
	// shape ids assigned during the sync above).
	s.applyMediaTiming()

	// Flush any authored animations into the timing tree (also after the sync,
	// so build-by-paragraph can count the target's paragraphs).
	s.applyAnimations()

	// Use the namespace-aware marshaler for PowerPoint compatibility
	return marshalSlide(s.slideXML)
}

// syncShapesToXML converts Go shapes to oxml types in the shape tree.
func (s *Slide) syncShapesToXML() {
	// Sniff missing media content types first: syncs triggered before the
	// first save (ReplaceText, Duplicate) embed media parts too.
	s.resolveMediaContentTypes()
	// Allocate the relationships API-created hyperlinks need before any shape is
	// marshaled, so their r:id is present when runToOxml / the shape builders
	// emit the a:hlinkClick. Idempotent: hyperlinks already backed by a rel are
	// left alone.
	s.allocateHyperlinkRels()
	if s.slideXML.CSld == nil {
		s.slideXML.CSld = &oxml.CommonSlideData{}
	}
	if s.slideXML.CSld.SpTree == nil {
		s.slideXML.CSld.SpTree = newShapeTree()
	}

	spTree := s.slideXML.CSld.SpTree

	// Loaded slide with removals: delete just the removed nodes from the parsed
	// tree (preserving all other content, including kinds the domain model does
	// not represent), then append any new shapes. Avoids the destructive full
	// rebuild below.
	if len(s.removedRefs) > 0 && !s.forceShapeRebuild {
		// Capture what the removed pic nodes reference before they go: their
		// shape ids (a generated timing tree must stop targeting them) and
		// their relationship ids (media/poster rels to garbage collect).
		removedSpids, removedRelIDs := collectRemovedPicRefs(spTree, s.removedRefs)
		spTree.RemoveChildren(s.removedRefs)
		s.reindexShapeRefsAfterRemoval(s.removedRefs)
		s.removedRefs = nil
		s.syncDirtyShapes(spTree)
		if len(s.shapes) > s.syncedShapes {
			s.appendShapesToXML(spTree, s.shapes[s.syncedShapes:])
		}
		s.pruneAutoTiming(removedSpids)
		s.gcSlideRels(removedRelIDs)
		s.resolveConnectorBindings()
		s.syncedShapes = len(s.shapes)
		s.shapesModified = false
		s.clearShapeDirt()
		return
	}

	// Loaded slide, in-place edits and appends only: flush dirty synced shapes
	// into their parsed nodes, then marshal just the new shapes into the parsed
	// tree. The full rebuild below regenerates the tree from the domain model,
	// which drops content the model does not represent (group shapes,
	// connectors) and re-numbers every existing shape — acceptable for decks
	// built programmatically, destructive for decks loaded from a file.
	if s.syncedShapes > 0 && !s.forceShapeRebuild && len(s.shapes) >= s.syncedShapes {
		s.syncDirtyShapes(spTree)
		s.appendShapesToXML(spTree, s.shapes[s.syncedShapes:])
		s.resolveConnectorBindings()
		s.syncedShapes = len(s.shapes)
		s.shapesModified = false
		s.clearShapeDirt()
		return
	}

	// Clear existing shapes and child order tracking. Connectors are cleared
	// too: they are materialized into s.shapes and re-emitted from the loop
	// below, so leaving the parsed nodes would duplicate them.
	spTree.Sp = nil
	spTree.GraphicFrame = nil
	spTree.Pic = nil
	spTree.GrpSp = nil
	spTree.CxnSp = nil
	spTree.ClearChildOrder()

	// The rebuild renumbers every shape and re-collects auto-play refs from
	// scratch via buildMediaPic below, so drop refs gathered by earlier syncs
	// (they hold stale ids and would duplicate media in the timing tree) and
	// flag any generated timing tree for regeneration.
	s.autoplayMedia = nil
	s.timingRegen = true

	// Convert each shape, seeding ids above anything the rebuild left in the
	// tree (AltContent/RawXML children keep their parsed ids): cNvPr ids must be
	// unique slide-wide (ST_DrawingElementId).
	shapeID := spTree.MaxShapeID() + 1
	if shapeID < 2 {
		shapeID = 2 // 1 belongs to the shape tree itself
	}
	allocID := func() uint32 {
		id := shapeID
		shapeID++
		return id
	}
	for _, shape := range s.shapes {
		// Record the id assigned to each shape so a connector bound to it can
		// resolve its cNvPr id after the loop (see resolveConnectorBindings) and
		// so ID() reports the saved id in-memory. Groups and connectors set their
		// own sourceID inside their builders.
		switch sh := shape.(type) {
		case *TextBox:
			id := allocID()
			spTree.Sp = append(spTree.Sp, textBoxToOxml(sh, id))
			sh.sourceID = id
		case *PlaceholderShape:
			id := allocID()
			spTree.Sp = append(spTree.Sp, placeholderToOxml(sh, id))
			sh.sourceID = id
		case *AutoShape:
			id := allocID()
			spTree.Sp = append(spTree.Sp, autoShapeToOxml(sh, id))
			sh.sourceID = id
		case *Table:
			id := allocID()
			spTree.GraphicFrame = append(spTree.GraphicFrame, tableToOxml(sh, id))
			sh.sourceID = id
		case *ChartFrame:
			id := allocID()
			spTree.GraphicFrame = append(spTree.GraphicFrame, chartFrameToOxml(sh, id))
			sh.sourceID = id
		case *SmartArtFrame:
			id := allocID()
			spTree.GraphicFrame = append(spTree.GraphicFrame, smartArtFrameToOxml(sh, id))
			sh.sourceID = id
		case *Picture:
			id := allocID()
			spTree.Pic = append(spTree.Pic, pictureToOxml(sh, id))
			sh.sourceID = id
		case *Video:
			id := allocID()
			spTree.Pic = append(spTree.Pic, s.buildMediaPic(&sh.mediaShape, id, mediaVideo))
			sh.sourceID = id
		case *Audio:
			id := allocID()
			spTree.Pic = append(spTree.Pic, s.buildMediaPic(&sh.mediaShape, id, mediaAudio))
			sh.sourceID = id
		case *GroupShape:
			// A domain-built group serializes as a real p:grpSp with its
			// children, ids allocated slide-wide (previously groups added via
			// AddShape were silently never written, C85).
			spTree.GrpSp = append(spTree.GrpSp, s.buildGroupNode(sh, allocID))
		case *Connector:
			spTree.CxnSp = append(spTree.CxnSp, connectorToOxml(sh, allocID()))
		}
	}

	// Every shape now has its assigned id, so connectors bound to shapes can
	// write their stCxn/endCxn (see resolveConnectorBindings).
	s.resolveConnectorBindings()

	// The rebuild regenerated the tree from the domain model, so media/image
	// relationships belonging to shapes that are gone are no longer referenced
	// by the slide XML — drop them so their parts can be garbage-collected at
	// save time (C221). gcSlideRels keeps every id the regenerated XML still
	// references.
	if s.partName != "" && s.presentation != nil {
		var removable []string
		for _, rel := range s.presentation.relationships[s.partName] {
			if rel != nil && removableRelType(rel.Type) {
				removable = append(removable, rel.ID)
			}
		}
		s.gcSlideRels(removable)
	}

	// The rebuild regenerates the whole tree from the domain model, so any
	// surgical bookkeeping recorded against the old tree is void. Leaving
	// syncedShapes at 0 keeps the slide in rebuild mode, where every domain
	// mutation is flushed on the next sync.
	s.syncedShapes = 0
	s.shapeRefs = nil
	s.removedRefs = nil
	s.shapesModified = false
	s.clearShapeDirt()
}

// resolveConnectorBindings writes the stCxn/endCxn bindings of API-created
// connectors into their parsed nodes, now that every shape on the slide has an
// id. A connector bound to a shape (via Connect/SetStartShape/SetEndShape)
// takes that shape's assigned cNvPr id; ends left free, and connectors
// materialized from a file (whose bindings are already in their nodes), are
// untouched — so an unmodified deck with existing connectors stays
// byte-identical.
func (s *Slide) resolveConnectorBindings() {
	// Connectors can live at the slide top level or inside a group
	// (GroupShape.AddConnector); forEachShape descends into groups so a grouped
	// connector's endpoint bindings resolve to the same assigned ids.
	forEachShape(s.shapes, func(sh Shape) {
		c, ok := sh.(*Connector)
		if !ok || c.sourceCxn == nil || c.sourceCxn.NvCxnSpPr == nil {
			return
		}
		if c.startShape == nil && c.endShape == nil {
			return
		}
		cnv := c.sourceCxn.NvCxnSpPr.CNvCxnSpPr
		if cnv == nil {
			cnv = &dml.CNvCxnSpPr{}
			c.sourceCxn.NvCxnSpPr.CNvCxnSpPr = cnv
		}
		if c.startShape != nil {
			if id := c.startShape.ID(); id != 0 {
				cnv.StCxn = &dml.Cxn{Id: id, Idx: c.startSite}
			}
		}
		if c.endShape != nil {
			if id := c.endShape.ID(); id != 0 {
				cnv.EndCxn = &dml.Cxn{Id: id, Idx: c.endSite}
			}
		}
	})
}

// reindexShapeRefsAfterRemoval rewrites shapeRefs from the pre-compaction
// indices they were recorded with to the indices the surviving children occupy
// after RemoveChildren compacted the typed slices: every removed same-kind
// child below a ref shifts it down by one. Without this, refs recorded before
// one removal target the wrong nodes in the next removal cycle.
func (s *Slide) reindexShapeRefsAfterRemoval(removed []oxml.ChildRef) {
	for i, ref := range s.shapeRefs {
		if ref.Index < 0 {
			continue
		}
		dec := 0
		for _, rem := range removed {
			if rem.Kind == ref.Kind && rem.Index < ref.Index {
				dec++
			}
		}
		if dec > 0 {
			s.shapeRefs[i] = oxml.ChildRef{Kind: ref.Kind, Index: ref.Index - dec}
		}
	}
}

// appendShapesToXML marshals newly added shapes into a parsed shape tree,
// assigning ids above everything already on the slide. Each appended shape's
// child reference is recorded in shapeRefs so a later removal (or in-place
// update) can target its node surgically instead of forcing a full rebuild;
// shapes the append path cannot express get a sentinel ref (Index -1) to keep
// shapeRefs aligned with the shapes slice.
func (s *Slide) appendShapesToXML(spTree *oxml.ShapeTree, shapes []Shape) {
	id := spTree.MaxShapeID() + 1
	if id < 2 {
		id = 2 // 1 belongs to the shape tree itself
	}
	allocID := func() uint32 {
		next := id
		id++
		return next
	}
	for _, shape := range shapes {
		ref := oxml.ChildRef{Index: -1}
		switch sh := shape.(type) {
		case *TextBox:
			spTree.AppendSp(textBoxToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildSp, Index: len(spTree.Sp) - 1}
		case *PlaceholderShape:
			spTree.AppendSp(placeholderToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildSp, Index: len(spTree.Sp) - 1}
		case *AutoShape:
			spTree.AppendSp(autoShapeToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildSp, Index: len(spTree.Sp) - 1}
		case *Table:
			gf := tableToOxml(sh, id)
			spTree.AppendGraphicFrame(gf)
			// Later row/cell mutations reach the XML via SyncXML.
			sh.sourceFrame = gf
			ref = oxml.ChildRef{Kind: oxml.ChildGraphicFrame, Index: len(spTree.GraphicFrame) - 1}
		case *ChartFrame:
			spTree.AppendGraphicFrame(chartFrameToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildGraphicFrame, Index: len(spTree.GraphicFrame) - 1}
		case *SmartArtFrame:
			spTree.AppendGraphicFrame(smartArtFrameToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildGraphicFrame, Index: len(spTree.GraphicFrame) - 1}
		case *Picture:
			spTree.AppendPic(pictureToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildPic, Index: len(spTree.Pic) - 1}
		case *Video:
			spTree.AppendPic(s.buildMediaPic(&sh.mediaShape, id, mediaVideo))
			ref = oxml.ChildRef{Kind: oxml.ChildPic, Index: len(spTree.Pic) - 1}
		case *Audio:
			spTree.AppendPic(s.buildMediaPic(&sh.mediaShape, id, mediaAudio))
			ref = oxml.ChildRef{Kind: oxml.ChildPic, Index: len(spTree.Pic) - 1}
		case *GroupShape:
			// Serialize a domain-built group appended to a loaded slide as a
			// real p:grpSp (previously a sentinel ref: silently never written,
			// C85). buildGroupNode allocates the ids itself, so the post-switch
			// id++ is skipped via continue-style handling below.
			spTree.AppendGrpSp(s.buildGroupNode(sh, allocID))
			s.shapeRefs = append(s.shapeRefs, oxml.ChildRef{Kind: oxml.ChildGrpSp, Index: len(spTree.GrpSp) - 1})
			continue
		case *Connector:
			spTree.AppendCxnSp(connectorToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildCxnSp, Index: len(spTree.CxnSp) - 1}
		}
		if ref.Index >= 0 {
			// Record the assigned id on the shape so a connector bound to it can
			// resolve its cNvPr id, and so ID() reports the saved id in-memory.
			if b := baseShapeOf(shape); b != nil {
				b.sourceID = id
			}
			id++
		}
		s.shapeRefs = append(s.shapeRefs, ref)
	}
}

// textBoxToOxml converts a TextBox to oxml.Shape.
