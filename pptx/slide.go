// Slide represents a slide in a presentation.
type Slide struct {
	presentation *Presentation
	layout       *SlideLayout
	partName     string
	// sxModel is the parsed slide part. For a slide loaded from a file it is
	// parsed lazily on first access (see sx): a slide round-tripped without
	// inspecting or editing it is never parsed, so the save writes the slide's
	// original bytes verbatim rather than building (and holding) a full model.
	// Reach it through sx(); the save path, sx() itself, validation, and slide
	// construction read/set sxModel + sxParsed directly so they do not trigger a
	// parse.
	sxModel *oxml.Slide
	// sxParsed records that the slide was materialized (parsed on access, or
	// built for a created slide). When sxModel is still nil at save time the
	// slide was never touched, so its original bytes pass through unchanged.
	sxParsed bool
	// sxParseErr holds the failure of a lazy re-parse of bytes loadSlides
	// already parsed — an impossible state that sx() reports by panicking
	// rather than by silently reading the slide as empty (C568).
	sxParseErr error
	index      int
	id         uint32
	relID      string
	// idExtLst preserves the extLst child of this slide's p:sldId entry in
	// presentation.xml, which is regenerated on every save (C225).
	idExtLst *oxml.ExtensionList
	// shapeCache holds the materialized Go-level shapes. It is populated lazily
	// by sx(); read it through shapeList() (which triggers the parse), and let
	// the internal sync machinery read/write it directly.
	shapeCache     []Shape
	shapesModified bool // true if shapes changed via Go API

	// syncedShapes counts the leading shapes already represented in sxModel
	// (the parsed shapes of a loaded slide). When only appends happened,
	// marshal() syncs just the new shapes into the parsed tree instead of
	// rebuilding it — a rebuild drops slide content the domain model cannot
	// represent (group shapes, connectors) and re-numbers every shape.
	syncedShapes int
	// forceShapeRebuild is set by structural edits the surgical/append sync
	// cannot express, forcing a full rebuild from the domain model.
	forceShapeRebuild bool
	// shapeRefs records, for each materialized (parsed) shape in shapes, the
	// child reference in the parsed shape tree it came from. It stays aligned
	// with shapes[:syncedShapes] so a removed shape can be deleted surgically.
	shapeRefs []oxml.ChildRef
	// removedRefs collects the parsed child references removed via RemoveShape,
	// applied at sync time by deleting just those nodes (preserving everything
	// else, including content the domain model cannot represent).
	removedRefs []oxml.ChildRef
	// autoplayMedia records the shape ids of auto-play video/audio added to the
	// slide, collected during the shape sync and used to build the timing tree.
	autoplayMedia []mediaTimingRef
	// autoTimingRefs is the full set of auto-play refs the current generated
	// timing tree was built from. Appends accumulate into it; a full rebuild
	// (which renumbers shape ids) resets it so the tree is regenerated from
	// the fresh ids.
	autoTimingRefs []mediaTimingRef
	// timingAutoGenerated marks the slide's timing tree as one this library
	// built for auto-play media. Only such trees may be regenerated; a timing
	// tree parsed from an opened file is never touched.
	timingAutoGenerated bool
	// timingRegen is set by a full shape rebuild: ids were renumbered and
	// autoplayMedia re-collected from scratch, so any generated timing tree
	// must be rebuilt (or dropped) from that complete set.
	timingRegen bool
	// pendingAnims holds animations added via AddAnimation that have not yet
	// been serialized into the timing tree; applyAnimations flushes them at
	// save. A slide with no pending animations never has its timing touched.
	pendingAnims []*Animation
}

// sx returns the parsed slide model, parsing it lazily from the slide part's
// original bytes on first access and materializing its Go-level shapes. A slide
// that is round-tripped without ever being accessed keeps sxModel nil, so on
// save its original bytes pass through verbatim. Open already validated the
// part (parse-then-discard), so a lazy parse here does not re-surface the
// malformed-slide error Open reports. Parsing never marks the slide modified,
// so an accessed-but-unedited slide still regenerates byte-identically. Returns
// nil only when the bytes are unavailable (a hand-built slide).
//
// If the bytes ARE present and the re-parse fails, that is in-memory corruption
// of bytes loadSlides already parsed successfully, and it panics with a
// diagnostic rather than returning nil. A nil model here reads as an empty
// slide: every shape gone, silently. docx's doc() has always made this choice
// for the identical state (C568); the three copies of this function now agree.
func (s *Slide) sx() *oxml.Slide {
	if s.sxModel == nil && !s.sxParsed {
		s.sxParsed = true
		raw := s.rawBytes()
		if raw == nil {
			return nil
		}
		m := &oxml.Slide{}
		m.Prolog = xmlb.CaptureProlog(raw)
		m.SelfClosingSpace = xmlb.DetectSelfClosingSpace(raw)
		m.CollapseEmpty = xmlb.DetectCollapsedEmptyElements(raw)
		if err := xmlb.UnmarshalWithSource(raw, m); err != nil {
			s.sxParseErr = err
		} else {
			s.sxModel = m
			s.materializeShapes()
		}
	}
	if s.sxParseErr != nil {
		panic(fmt.Sprintf("pptx: lazy parse of slide part %s failed: %v "+
			"(Open validated the same bytes, so this indicates in-memory corruption)",
			s.partName, s.sxParseErr))
	}
	return s.sxModel
}

// rawBytes returns the slide part's original bytes from the presentation's
// still-open reader, or nil when the slide was not loaded from a package (a
// created slide) or its part is unavailable. It is the source for both the lazy
// parse (sx) and the save-time passthrough of an unmodified slide.
func (s *Slide) rawBytes() []byte {
	if s.presentation == nil || s.presentation.reader == nil {
		return nil
	}
	f := s.presentation.reader.GetFile(s.partName)
	if f == nil {
		return nil
	}
	raw, err := f.ReadAll()
	if err != nil {
		return nil
	}
	return raw
}

// ensureModel returns the slide model for a mutator that is about to edit it
// directly, materializing an existing slide's parsed content first (so the edit
// preserves it) and allocating an empty model only when the slide has no bytes
// to parse. Mutators call this before editing so a never-parsed slide is not
// silently replaced with an empty one.
//
// It also records the edit. Such mutators (SetTransition, the background
// setters, SetName) need no flag to persist — materializing the model is itself
// what makes the save regenerate the part — so nothing else notes that the
// slide changed, and the modification timestamp would miss it. Read paths must
// use sx()/materialize() instead; ensureModel means "I am about to write".
func (s *Slide) ensureModel() *oxml.Slide {
	s.presentation.markModelEdited()
	return s.materialize()
}

// materialize returns the slide model, parsing it if needed and allocating an
// empty one for a slide with no bytes, without recording an edit. It is
// ensureModel without the write intent, for the save path (which must be able to
// marshal a slide nobody touched).
func (s *Slide) materialize() *oxml.Slide {
	if s.sx() == nil {
		s.sxModel = newSlideXML()
		s.sxParsed = true
	}
	return s.sxModel
}

// shapeList returns the slide's materialized shapes for read access, triggering
// the lazy parse (see sx) so a never-accessed slide reports its real shapes.
func (s *Slide) shapeList() []Shape {
	s.sx()
	return s.shapeCache
}

// Index returns the 0-based index of the slide in the presentation.
func (s *Slide) Index() int {
	return s.index
}

// RelID returns the slide's presentation-level relationship id (the r:id of its
// p:sldId entry in presentation.xml). For a slide loaded from a file this is its
// stored id; a slide created through this package is assigned a provisional id
// when it is added (not the empty string), which the deck's first save may
// reassign by slide order. It is the identifier a custom show references (see
// Presentation.AddCustomShow) — a reference recorded before save is remapped
// through that reassignment, so it keeps resolving to the same slide.
func (s *Slide) RelID() string {
	return s.relID
}

// Name returns the name of the slide, if any.
func (s *Slide) Name() string {
	if m := s.sx(); m != nil && m.CSld != nil {
		return m.CSld.Name
	}
	return ""
}

// SetName sets the name of the slide.
func (s *Slide) SetName(name string) {
	m := s.ensureModel()
	if m.CSld == nil {
		m.CSld = &oxml.CommonSlideData{}
	}
	m.CSld.Name = name
	s.shapesModified = true
}

// Layout returns the slide layout, or nil if none is set.
func (s *Slide) Layout() *SlideLayout {
	return s.layout
}

// Shapes returns all shapes on the slide.
func (s *Slide) Shapes() []Shape {
	return s.shapeList()
}

// AddShape adds a shape to the slide. It returns an error for shape types the
// library cannot serialize (previously such shapes were accepted and then
// silently dropped on save).
//
// The accepted types are TextBox, PlaceholderShape, AutoShape, Table, Picture,
// Video, Audio, GroupShape and Connector.
//
// ChartFrame, SmartArtFrame and OLEObjectFrame are rejected: they own parts and
// relationships as well as a shape-tree node, so they are created through
// AddChart, AddSmartArt and AddOLEObject rather than assembled and handed over.
// RemoveShape does accept them, so a frame removed by mistake cannot be re-added
// as the same object — recreate it through its Add* constructor.
func (s *Slide) AddShape(shape Shape) error {
	switch shape.(type) {
	case *TextBox, *PlaceholderShape, *AutoShape, *Table, *Picture, *Video, *Audio, *GroupShape, *Connector:
		s.addShape(shape)
		return nil
	default:
		return fmt.Errorf("pptx: AddShape: unsupported shape type %T", shape)
	}
}

// addShape appends a shape the sync paths know how to serialize. It first
// materializes the slide (sx) so a shape added to a never-accessed loaded slide
// extends the slide's existing shapes rather than replacing them, and so the
// save regenerates the part (sxModel is now set) instead of passing the
// original bytes through and dropping the addition.
func (s *Slide) addShape(shape Shape) {
	s.sx()
	s.setShapeBackRef(shape)
	s.shapeCache = append(s.shapeCache, shape)
	s.shapesModified = true
}

// RemoveShape removes a shape from the slide. On a slide loaded from a file the
// removed shape's node is deleted surgically from the parsed tree on save, so
// other content (including group shapes, connectors, and other kinds the domain
// model does not represent) is preserved.
func (s *Slide) RemoveShape(shape Shape) {
	s.sx()
	for i, sh := range s.shapeCache {
		if sh != shape {
			continue
		}
		switch {
		case i < s.syncedShapes && i < len(s.shapeRefs):
			// A synced shape: mark its source node for surgical deletion. A
			// sentinel ref (Index -1) means the shape never made it into the
			// tree, so there is nothing to delete there.
			if ref := s.shapeRefs[i]; ref.Index >= 0 {
				s.removedRefs = append(s.removedRefs, ref)
			}
			s.shapeRefs = append(s.shapeRefs[:i], s.shapeRefs[i+1:]...)
			s.syncedShapes--
		case i < s.syncedShapes:
			// Parsed shape without a tracked source (no child-order info):
			// fall back to a full rebuild.
			s.forceShapeRebuild = true
		}
		// Shapes added after the last sync were never written; dropping them
		// from the slice is sufficient.
		s.shapeCache = append(s.shapeCache[:i], s.shapeCache[i+1:]...)
		s.shapesModified = true
		return
	}
}

// AddTextBox adds a text box shape to the slide.
func (s *Slide) AddTextBox() *TextBox {
	tb := NewTextBox()
	s.addShape(tb)
	return tb
}

// AddPicture adds a picture shape to the slide, reading the image from
// imagePath. It returns an error if the file cannot be read (previously the
// path was stored without reading it, so a nonexistent file returned no error
// and produced a blip with no image reference), or if its bytes are not an
// image format this package embeds. The image data is embedded as a media part
// when the presentation is saved.
//
// An .svg file is embedded the way PowerPoint expects an SVG: a transparent
// raster fallback in a:blip@r:embed with the SVG itself referenced through the
// asvg:svgBlip extension, matching docx's Run.AddImage and xlsx's
// Sheet.AddImage. Supply your own fallback with Picture.SetSVGImageData.
//
// The picture frame defaults to the image's intrinsic size at 96 DPI (decoded
// from the PNG/JPEG/GIF header; other formats fall back to 4x3 inches), so the
// picture is visible without further setup. Call SetSize/SetPosition on the
// returned Picture to place it explicitly.
func (s *Slide) AddPicture(imagePath string) (*Picture, error) {
	pic := NewPicture()
	if err := pic.SetImage(imagePath); err != nil {
		return nil, err
	}
	s.sizePictureToImage(pic)
	s.addShape(pic)
	return pic, nil
}

// AddPictureFromBytes adds a picture to the slide from raw image bytes and
// their content type (e.g. "image/png"), embedding the image in the .pptx on
// save. This is the byte-slice counterpart to AddPicture (which reads a file)
// and mirrors AddVideo/AddAudio. The frame defaults to the image's intrinsic
// pixel size at 96 DPI, or 4x3 inches when the dimensions cannot be decoded;
// override it with Picture.SetSize.
//
// It fails with an error when the data is empty or is not one of the image
// formats this package embeds. That check used to be deferred to save and then
// never happened, so garbage bytes under an "image/png" content type saved
// clean and produced an unreadable media part while this godoc promised
// otherwise (C441).
//
// SVG data — either declared with an "image/svg+xml" content type or recognized
// by content — is embedded with a transparent raster fallback and an
// asvg:svgBlip extension, the structure PowerPoint needs. Previously it emitted
// a bare a:blip pointing straight at the .svg part, which most PowerPoint
// versions render as nothing at all, even though docx and xlsx built the
// conformant pair from the same call (C387). Supply your own fallback with
// Picture.SetSVGImageData.
func (s *Slide) AddPictureFromBytes(data []byte, contentType string) (*Picture, error) {
	if len(data) == 0 {
		return nil, fmt.Errorf("pptx: AddPictureFromBytes: image data is empty")
	}
	pic := NewPicture()
	if err := pic.setImageBytes("AddPictureFromBytes", data, contentType); err != nil {
		return nil, err
	}
	s.sizePictureToImage(pic)
	s.addShape(pic)
	return pic, nil
}

// sizePictureToImage gives a freshly added picture its default frame: the
// intrinsic pixel size of the image at 96 DPI, or 4x3 inches when the format
// carries no decodable header. For an SVG the size comes from the SVG root
// rather than from the transparent raster fallback, which is 1x1.
func (s *Slide) sizePictureToImage(pic *Picture) {
	if len(pic.svgData) > 0 {
		w, h := svgIntrinsicSizeEMU(pic.svgData)
		pic.SetSize(w, h)
		return
	}
	if w, h, ok := nativeImageSize(pic.imageData); ok {
		pic.SetSize(w, h)
		return
	}
	pic.SetSize(dml.Inches(4), dml.Inches(3))
}

