// marshal converts the slide to XML bytes. It regenerates the part from the
// (possibly edited) model; the save path calls it only for a slide whose model
// was materialized, so an untouched slide passes its original bytes through
// without ever reaching here.
func (s *Slide) marshal() ([]byte, error) {
	// materialize, not ensureModel: serializing a slide is not editing it, and
	// ensureModel would record a model edit for every slide on every save.
	s.materialize()

	// Reject media that cannot become a valid package part (no data, or no
	// recognizable content type) before any of it is written.
	if err := s.validateMediaShapes(); err != nil {
		return nil, err
	}

	// Only sync Go shapes to XML when shapes were modified via the API: added
	// or removed (shapesModified), or mutated in place (dirty flags). When
	// loading from a file, the slideXML already contains the parsed shapes.
	if s.shapesModified || s.hasDirtyShapes() {
		s.syncShapesToXML()
	}

	// Process any pending image replacements after the XML tree is up to date.
	// This modifies the XML directly, converting p:sp elements to p:pic elements
	// or swapping the blip reference on existing pictures.
	if err := s.processPendingImages(); err != nil {
		return nil, err
	}

	// Build the timing tree for any auto-play media added to the slide (needs the
	// shape ids assigned during the sync above).
	s.applyMediaTiming()

	// Flush any authored animations into the timing tree (also after the sync,
	// so build-by-paragraph can count the target's paragraphs).
	s.applyAnimations()

	// Use the namespace-aware marshaler for PowerPoint compatibility
	return marshalSlide(s.sx())
}

// syncShapesToXML converts Go shapes to oxml types in the shape tree.
func (s *Slide) syncShapesToXML() {
	// Sniff missing media content types first: syncs triggered before the
	// first save (ReplaceText, Duplicate) embed media parts too.
	s.resolveMediaContentTypes()
	// Allocate the relationships API-created hyperlinks need before any shape is
	// marshaled, so their r:id is present when runToOxml / the shape builders
	// emit the a:hlinkClick. Idempotent: hyperlinks already backed by a rel are
	// left alone.
	s.allocateHyperlinkRels()
	if s.sx().CSld == nil {
		s.sx().CSld = &oxml.CommonSlideData{}
	}
	if s.sx().CSld.SpTree == nil {
		s.sx().CSld.SpTree = newShapeTree()
	}

	spTree := s.sx().CSld.SpTree

	// Loaded slide with removals: delete just the removed nodes from the parsed
	// tree (preserving all other content, including kinds the domain model does
	// not represent), then append any new shapes. Avoids the destructive full
	// rebuild below.
	if len(s.removedRefs) > 0 && !s.forceShapeRebuild {
		// Capture what the removed pic nodes reference before they go: their
		// shape ids (a generated timing tree must stop targeting them) and
		// their relationship ids (media/poster rels to garbage collect).
		removedSpids, removedRelIDs := collectRemovedPicRefs(spTree, s.removedRefs)
		spTree.RemoveChildren(s.removedRefs)
		s.reindexShapeRefsAfterRemoval(s.removedRefs)
		s.removedRefs = nil
		s.syncDirtyShapes(spTree)
		if len(s.shapeCache) > s.syncedShapes {
			s.appendShapesToXML(spTree, s.shapeCache[s.syncedShapes:])
		}
		s.pruneAutoTiming(removedSpids)
		s.gcSlideRels(removedRelIDs)
		s.resolveConnectorBindings()
		s.syncedShapes = len(s.shapeCache)
		s.shapesModified = false
		s.clearShapeDirt()
		return
	}

	// Loaded slide, in-place edits and appends only: flush dirty synced shapes
	// into their parsed nodes, then marshal just the new shapes into the parsed
	// tree. The full rebuild below regenerates the tree from the domain model,
	// which drops content the model does not represent (group shapes,
	// connectors) and re-numbers every existing shape — acceptable for decks
	// built programmatically, destructive for decks loaded from a file.
	if s.syncedShapes > 0 && !s.forceShapeRebuild && len(s.shapeCache) >= s.syncedShapes {
		s.syncDirtyShapes(spTree)
		s.appendShapesToXML(spTree, s.shapeCache[s.syncedShapes:])
		s.resolveConnectorBindings()
		s.syncedShapes = len(s.shapeCache)
		s.shapesModified = false
		s.clearShapeDirt()
		return
	}

	// Clear existing shapes and child order tracking. Connectors are cleared
	// too: they are materialized into s.shapeCache and re-emitted from the loop
	// below, so leaving the parsed nodes would duplicate them.
	spTree.Sp = nil
	spTree.GraphicFrame = nil
	spTree.Pic = nil
	spTree.GrpSp = nil
	spTree.CxnSp = nil
	spTree.ClearChildOrder()

	// The rebuild renumbers every shape and re-collects auto-play refs from
	// scratch via buildMediaPic below, so drop refs gathered by earlier syncs
	// (they hold stale ids and would duplicate media in the timing tree) and
	// flag any generated timing tree for regeneration.
	s.autoplayMedia = nil
	s.timingRegen = true

	// Convert each shape, seeding ids above anything the rebuild left in the
	// tree (AltContent/RawXML children keep their parsed ids): cNvPr ids must be
	// unique slide-wide (ST_DrawingElementId).
	shapeID := spTree.MaxShapeID() + 1
	if shapeID < 2 {
		shapeID = 2 // 1 belongs to the shape tree itself
	}
	allocID := func() uint32 {
		id := shapeID
		shapeID++
		return id
	}
	for _, shape := range s.shapeCache {
		// Record the id assigned to each shape so a connector bound to it can
		// resolve its cNvPr id after the loop (see resolveConnectorBindings) and
		// so ID() reports the saved id in-memory. Groups and connectors set their
		// own sourceID inside their builders.
		switch sh := shape.(type) {
		case *TextBox:
			id := allocID()
			spTree.Sp = append(spTree.Sp, textBoxToOxml(sh, id))
			sh.sourceID = id
		case *PlaceholderShape:
			id := allocID()
			spTree.Sp = append(spTree.Sp, placeholderToOxml(sh, id))
			sh.sourceID = id
		case *AutoShape:
			id := allocID()
			spTree.Sp = append(spTree.Sp, autoShapeToOxml(sh, id))
			sh.sourceID = id
		case *Table:
			id := allocID()
			spTree.GraphicFrame = append(spTree.GraphicFrame, tableToOxml(sh, id))
			sh.sourceID = id
		case *ChartFrame:
			id := allocID()
			spTree.GraphicFrame = append(spTree.GraphicFrame, chartFrameToOxml(sh, id))
			sh.sourceID = id
		case *SmartArtFrame:
			id := allocID()
			spTree.GraphicFrame = append(spTree.GraphicFrame, smartArtFrameToOxml(sh, id))
			sh.sourceID = id
		case *OLEObjectFrame:
			id := allocID()
			spTree.GraphicFrame = append(spTree.GraphicFrame, oleObjectFrameToOxml(sh, id))
			sh.sourceID = id
		case *Picture:
			id := allocID()
			spTree.Pic = append(spTree.Pic, pictureToOxml(sh, id))
			sh.sourceID = id
		case *Video:
			id := allocID()
			spTree.Pic = append(spTree.Pic, s.buildMediaPic(&sh.mediaShape, id, mediaVideo))
			sh.sourceID = id
		case *Audio:
			id := allocID()
			spTree.Pic = append(spTree.Pic, s.buildMediaPic(&sh.mediaShape, id, mediaAudio))
			sh.sourceID = id
		case *GroupShape:
			// A domain-built group serializes as a real p:grpSp with its
			// children, ids allocated slide-wide (previously groups added via
			// AddShape were silently never written, C85).
			spTree.GrpSp = append(spTree.GrpSp, s.buildGroupNode(sh, allocID))
		case *Connector:
			spTree.CxnSp = append(spTree.CxnSp, connectorToOxml(sh, allocID()))
		}
	}

	// Every shape now has its assigned id, so connectors bound to shapes can
	// write their stCxn/endCxn (see resolveConnectorBindings).
	s.resolveConnectorBindings()

	// The rebuild regenerated the tree from the domain model, so media/image
	// relationships belonging to shapes that are gone are no longer referenced
	// by the slide XML — drop them so their parts can be garbage-collected at
	// save time (C221). gcSlideRels keeps every id the regenerated XML still
	// references.
	if s.partName != "" && s.presentation != nil {
		var removable []string
		for _, rel := range s.presentation.relationships[s.partName] {
			if rel != nil && removableRelType(rel.Type) {
				removable = append(removable, rel.ID)
			}
		}
		s.gcSlideRels(removable)
	}

	// The rebuild regenerates the whole tree from the domain model, so any
	// surgical bookkeeping recorded against the old tree is void. Leaving
	// syncedShapes at 0 keeps the slide in rebuild mode, where every domain
	// mutation is flushed on the next sync.
	s.syncedShapes = 0
	s.shapeRefs = nil
	s.removedRefs = nil
	s.shapesModified = false
	s.clearShapeDirt()
}

// resolveConnectorBindings writes the stCxn/endCxn bindings of API-created
// connectors into their parsed nodes, now that every shape on the slide has an
// id. A connector bound to a shape (via Connect/SetStartShape/SetEndShape)
// takes that shape's assigned cNvPr id; ends left free, and connectors
// materialized from a file (whose bindings are already in their nodes), are
// untouched — so an unmodified deck with existing connectors stays
// byte-identical.
func (s *Slide) resolveConnectorBindings() {
	// Connectors can live at the slide top level or inside a group
	// (GroupShape.AddConnector); forEachShape descends into groups so a grouped
	// connector's endpoint bindings resolve to the same assigned ids.
	forEachShape(s.shapeCache, func(sh Shape) {
		c, ok := sh.(*Connector)
		if !ok || c.sourceCxn == nil || c.sourceCxn.NvCxnSpPr == nil {
			return
		}
		if c.startShape == nil && c.endShape == nil {
			return
		}
		cnv := c.sourceCxn.NvCxnSpPr.CNvCxnSpPr
		if cnv == nil {
			cnv = &dml.CNvCxnSpPr{}
			c.sourceCxn.NvCxnSpPr.CNvCxnSpPr = cnv
		}
		if c.startShape != nil {
			if id := c.startShape.ID(); id != 0 {
				cnv.StCxn = &dml.Cxn{Id: id, Idx: c.startSite}
			}
		}
		if c.endShape != nil {
			if id := c.endShape.ID(); id != 0 {
				cnv.EndCxn = &dml.Cxn{Id: id, Idx: c.endSite}
			}
		}
	})
}

// reindexShapeRefsAfterRemoval rewrites shapeRefs from the pre-compaction
// indices they were recorded with to the indices the surviving children occupy
// after RemoveChildren compacted the typed slices: every removed same-kind
// child below a ref shifts it down by one. Without this, refs recorded before
// one removal target the wrong nodes in the next removal cycle.
func (s *Slide) reindexShapeRefsAfterRemoval(removed []oxml.ChildRef) {
	for i, ref := range s.shapeRefs {
		if ref.Index < 0 {
			continue
		}
		dec := 0
		for _, rem := range removed {
			if rem.Kind == ref.Kind && rem.Index < ref.Index {
				dec++
			}
		}
		if dec > 0 {
			s.shapeRefs[i] = oxml.ChildRef{Kind: ref.Kind, Index: ref.Index - dec}
		}
	}
}

// appendShapesToXML marshals newly added shapes into a parsed shape tree,
// assigning ids above everything already on the slide. Each appended shape's
// child reference is recorded in shapeRefs so a later removal (or in-place
// update) can target its node surgically instead of forcing a full rebuild;
// shapes the append path cannot express get a sentinel ref (Index -1) to keep
// shapeRefs aligned with the shapes slice.
func (s *Slide) appendShapesToXML(spTree *oxml.ShapeTree, shapes []Shape) {
	id := spTree.MaxShapeID() + 1
	if id < 2 {
		id = 2 // 1 belongs to the shape tree itself
	}
	allocID := func() uint32 {
		next := id
		id++
		return next
	}
	for _, shape := range shapes {
		ref := oxml.ChildRef{Index: -1}
		switch sh := shape.(type) {
		case *TextBox:
			spTree.AppendSp(textBoxToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildSp, Index: len(spTree.Sp) - 1}
		case *PlaceholderShape:
			spTree.AppendSp(placeholderToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildSp, Index: len(spTree.Sp) - 1}
		case *AutoShape:
			spTree.AppendSp(autoShapeToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildSp, Index: len(spTree.Sp) - 1}
		case *Table:
			gf := tableToOxml(sh, id)
			spTree.AppendGraphicFrame(gf)
			// Later row/cell mutations are auto-flushed into this frame on save
			// (SyncXML forces the flush earlier but is not required).
			sh.sourceFrame = gf
			ref = oxml.ChildRef{Kind: oxml.ChildGraphicFrame, Index: len(spTree.GraphicFrame) - 1}
		case *ChartFrame:
			spTree.AppendGraphicFrame(chartFrameToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildGraphicFrame, Index: len(spTree.GraphicFrame) - 1}
		case *SmartArtFrame:
			spTree.AppendGraphicFrame(smartArtFrameToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildGraphicFrame, Index: len(spTree.GraphicFrame) - 1}
		case *OLEObjectFrame:
			spTree.AppendGraphicFrame(oleObjectFrameToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildGraphicFrame, Index: len(spTree.GraphicFrame) - 1}
		case *Picture:
			spTree.AppendPic(pictureToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildPic, Index: len(spTree.Pic) - 1}
		case *Video:
			spTree.AppendPic(s.buildMediaPic(&sh.mediaShape, id, mediaVideo))
			ref = oxml.ChildRef{Kind: oxml.ChildPic, Index: len(spTree.Pic) - 1}
		case *Audio:
			spTree.AppendPic(s.buildMediaPic(&sh.mediaShape, id, mediaAudio))
			ref = oxml.ChildRef{Kind: oxml.ChildPic, Index: len(spTree.Pic) - 1}
		case *GroupShape:
			// Serialize a domain-built group appended to a loaded slide as a
			// real p:grpSp (previously a sentinel ref: silently never written,
			// C85). buildGroupNode allocates the ids itself, so the post-switch
			// id++ is skipped via continue-style handling below.
			spTree.AppendGrpSp(s.buildGroupNode(sh, allocID))
			s.shapeRefs = append(s.shapeRefs, oxml.ChildRef{Kind: oxml.ChildGrpSp, Index: len(spTree.GrpSp) - 1})
			continue
		case *Connector:
			spTree.AppendCxnSp(connectorToOxml(sh, id))
			ref = oxml.ChildRef{Kind: oxml.ChildCxnSp, Index: len(spTree.CxnSp) - 1}
		}
		if ref.Index >= 0 {
			// Record the assigned id on the shape so a connector bound to it can
			// resolve its cNvPr id, and so ID() reports the saved id in-memory.
			if b := baseShapeOf(shape); b != nil {
				b.sourceID = id
			}
			id++
		}
		s.shapeRefs = append(s.shapeRefs, ref)
	}
}

// textBoxToOxml converts a TextBox to oxml.Shape.
func textBoxToOxml(tb *TextBox, id uint32) *oxml.Shape {
	name := tb.Name()
	if name == "" {
		name = "TextBox"
	}

	x, y := tb.Position()
	w, h := tb.Size()

	sp := &oxml.Shape{
		NvSpPr: &oxml.NvSpPr{
			CNvPr: &dml.CNvPr{
				Id:   id,
				Name: name,
			},
			CNvSpPr: &dml.CNvSpPr{
				TxBox: true,
			},
			NvPr: &oxml.NvPr{},
		},
		SpPr: &dml.SpPr{
			Xfrm: &dml.Xfrm{
				Off: &dml.OffXML{X: int64(x), Y: int64(y)},
				Ext: &dml.ExtXML{Cx: int64(w), Cy: int64(h)},
			},
			PrstGeom: &dml.PrstGeom{
				Prst:  "rect",
				AvLst: &dml.AvLst{},
			},
		},
	}

	// Carry any fill/line/shadow set via SetFill/SetLine/SetShadow into the XML
	// (previously textBoxToOxml ignored tb.spPr entirely, so those setters were
	// silent no-ops).
	applyShapeStyle(sp.SpPr, &tb.spPr)

	if tb.hyperlink != nil {
		sp.NvSpPr.CNvPr.HlinkClick = hyperlinkToXML(tb.hyperlink)
	}

	if tb.textFrame != nil {
		sp.TxBody = textFrameToOxml(tb.textFrame)
	}

	return sp
}

// applyShapeStyle copies the fill, line, and effect properties that a domain
// shape stored (via Fill/Line/Shadow ApplyToSpPr) into the SpPr being
// marshaled. Every fill kind is copied, not just SolidFill, so gradient,
// pattern, and no-fill values are not dropped.
// mergeLn overlays the line members the domain model represents (width, cap,
// compound, alignment, fill, dash) onto the parsed a:ln and returns it.
//
// Assigning src wholesale — which is what SetLineWidth/SetLineColor/SetLineDash
// and Connector.SetLine used to cause — replaced the parsed line with the three
// properties dml.Line models, so a connector with cap="rnd" and a:headEnd /
// a:tailEnd lost both arrowheads and its cap on a width change. Arrowheads are
// the normal case for connectors, and the same path styles AutoShape and
// TextBox lines (C417).
func mergeLn(dst, src *dml.Ln) *dml.Ln {
	if dst == nil {
		return src
	}
	if src.W != nil {
		dst.W = src.W
	}
	if src.Cap != "" {
		dst.Cap = src.Cap
	}
	if src.Cmpd != "" {
		dst.Cmpd = src.Cmpd
	}
	if src.Algn != "" {
		dst.Algn = src.Algn
	}
	// The line fill is an exclusive choice, so a set member replaces the whole
	// group rather than joining it.
	if src.NoFill != nil || src.SolidFill != nil || src.GradFill != nil || src.PattFill != nil {
		dst.NoFill, dst.SolidFill, dst.GradFill, dst.PattFill = nil, nil, nil, nil
		switch {
		case src.NoFill != nil:
			dst.NoFill = src.NoFill
		case src.SolidFill != nil:
			dst.SolidFill = src.SolidFill
		case src.GradFill != nil:
			dst.GradFill = src.GradFill
		case src.PattFill != nil:
			dst.PattFill = src.PattFill
		}
	}
	// So is the dash: a preset dash displaces a parsed custom one.
	if src.PrstDash != nil {
		dst.PrstDash, dst.CustDash = src.PrstDash, nil
	} else if src.CustDash != nil {
		dst.PrstDash, dst.CustDash = nil, src.CustDash
	}
	// And the join.
	if src.Round != nil || src.Bevel != nil || src.Miter != nil {
		dst.Round, dst.Bevel, dst.Miter = src.Round, src.Bevel, src.Miter
	}
	if src.HeadEnd != nil {
		dst.HeadEnd = src.HeadEnd
	}
	if src.TailEnd != nil {
		dst.TailEnd = src.TailEnd
	}
	if src.ExtLst != nil {
		dst.ExtLst = src.ExtLst
	}
	return dst
}

func applyShapeStyle(dst *dml.SpPr, src *dml.SpPr) {
	if src == nil {
		return
	}
	// Fill is an exclusive choice (EG_FillProperties): a shape carries at most
	// one fill element. When the overlay sets any fill member it replaces the
	// destination's fill atomically — clear every competing member first, so a
	// shape parsed with <a:noFill/> that is given a solid fill does not end up
	// with both (which is schema-invalid).
	if srcHasFill(src) {
		dst.NoFill, dst.SolidFill, dst.GradFill = nil, nil, nil
		dst.PattFill, dst.BlipFill, dst.GrpFill = nil, nil, nil
		switch {
		case src.NoFill != nil:
			dst.NoFill = src.NoFill
		case src.SolidFill != nil:
			dst.SolidFill = src.SolidFill
		case src.GradFill != nil:
			dst.GradFill = src.GradFill
		case src.PattFill != nil:
			dst.PattFill = src.PattFill
		case src.BlipFill != nil:
			dst.BlipFill = src.BlipFill
		case src.GrpFill != nil:
			dst.GrpFill = src.GrpFill
		}
	}
	if src.Ln != nil {
		dst.Ln = mergeLn(dst.Ln, src.Ln)
	}
	// Effects merge per member: the overlay starts empty for a materialized
	// shape, so setting one effect (glow, shadow, reflection, soft edge) must
	// add to — never replace — the effects already parsed on the node.
	if src.EffectLst != nil {
		mergeEffectLst(dst, src.EffectLst)
	}
	if src.EffectDag != nil {
		dst.EffectDag = src.EffectDag
	}
	if src.Scene3d != nil {
		dst.Scene3d = src.Scene3d
	}
	// sp3d (3D bevel) merges per member for the same reason as the effect list.
	if src.Sp3d != nil {
		mergeSp3d(dst, src.Sp3d)
	}
}

// srcHasFill reports whether the SpPr carries any member of the EG_FillProperties
// exclusive choice.
func srcHasFill(sp *dml.SpPr) bool {
	return sp.NoFill != nil || sp.SolidFill != nil || sp.GradFill != nil ||
		sp.PattFill != nil || sp.BlipFill != nil || sp.GrpFill != nil
}

// mergeEffectLst copies each effect set on src onto dst's effect list,
// allocating one when absent. Members src does not set are left as parsed, so
// setting one effect does not drop effects already on the shape.
func mergeEffectLst(dst *dml.SpPr, src *dml.EffectLst) {
	if dst.EffectLst == nil {
		dst.EffectLst = &dml.EffectLst{}
	}
	d := dst.EffectLst
	if src.Blur != nil {
		d.Blur = src.Blur
	}
	if src.FillOverlay != nil {
		d.FillOverlay = src.FillOverlay
	}
	if src.Glow != nil {
		d.Glow = src.Glow
	}
	if src.InnerShdw != nil {
		d.InnerShdw = src.InnerShdw
	}
	if src.OuterShdw != nil {
		d.OuterShdw = src.OuterShdw
	}
	if src.PrstShdw != nil {
		d.PrstShdw = src.PrstShdw
	}
	if src.Reflection != nil {
		d.Reflection = src.Reflection
	}
	if src.SoftEdge != nil {
		d.SoftEdge = src.SoftEdge
	}
}

// mergeSp3d copies each 3D property set on src onto dst's sp3d, allocating one
// when absent. Properties src does not set are left as parsed, so setting one
// (e.g. a top bevel) does not drop 3D properties already on the shape.
func mergeSp3d(dst *dml.SpPr, src *dml.Sp3d) {
	if dst.Sp3d == nil {
		dst.Sp3d = src
		return
	}
	d := dst.Sp3d
	if src.Z != 0 {
		d.Z = src.Z
	}
	if src.ExtrusionH != 0 {
		d.ExtrusionH = src.ExtrusionH
	}
	if src.ContourW != 0 {
		d.ContourW = src.ContourW
	}
	if src.PrstMaterial != "" {
		d.PrstMaterial = src.PrstMaterial
	}
	if src.BevelT != nil {
		d.BevelT = src.BevelT
	}
	if src.BevelB != nil {
		d.BevelB = src.BevelB
	}
	if src.ExtrusionClr != nil {
		d.ExtrusionClr = src.ExtrusionClr
	}
	if src.ContourClr != nil {
		d.ContourClr = src.ContourClr
	}
}

// placeholderToOxml converts a PlaceholderShape to oxml.Shape.
func placeholderToOxml(ph *PlaceholderShape, id uint32) *oxml.Shape {
	name := ph.Name()
	if name == "" {
		name = string(ph.phType)
	}

	sp := &oxml.Shape{
		NvSpPr: &oxml.NvSpPr{
			CNvPr: &dml.CNvPr{
				Id:   id,
				Name: name,
			},
			CNvSpPr: &dml.CNvSpPr{},
			NvPr: &oxml.NvPr{
				Ph: &oxml.Placeholder{
					Type:   string(ph.phType),
					Orient: string(ph.orientation),
					Sz:     string(ph.size),
					Idx:    ph.idx,
				},
			},
		},
		SpPr: &dml.SpPr{},
	}

	// Furniture placeholders (footer/number/date) omit xfrm so PowerPoint
	// inherits geometry from the layout placeholder of the same type; every
	// other placeholder carries its explicit position and size.
	if !ph.inheritGeometry {
		x, y := ph.Position()
		w, h := ph.Size()
		sp.SpPr.Xfrm = &dml.Xfrm{
			Off: &dml.OffXML{X: int64(x), Y: int64(y)},
			Ext: &dml.ExtXML{Cx: int64(w), Cy: int64(h)},
		}
	}

	if ph.hyperlink != nil {
		sp.NvSpPr.CNvPr.HlinkClick = hyperlinkToXML(ph.hyperlink)
	}

	switch {
	case ph.fieldType != "":
		sp.TxBody = fieldTextBody(ph.fieldType, ph.fieldText)
	case ph.textFrame != nil:
		sp.TxBody = textFrameToOxml(ph.textFrame)
	}

	return sp
}

// fieldGUIDs are stable per-field-type ids for the required a:fld id
// attribute. PowerPoint uses random GUIDs but does not require uniqueness
// across slides for these auto fields; fixed values keep spine's output
// deterministic.
var fieldGUIDs = map[string]string{
	"slidenum": "{4A9C4C6E-5B2A-4C1D-9E8F-1A2B3C4D5E6F}",
	"datetime": "{7B1D2E3F-4A5B-4C6D-8E9F-0A1B2C3D4E5F}",
}

// fieldTextBody builds a text body whose single paragraph is an auto-updating
// field (a:fld) — used by slide-number and date furniture placeholders. The
// fallback text is what PowerPoint shows until it recalculates the field.
func fieldTextBody(fieldType, fallback string) *dml.TxBody {
	id := fieldGUIDs[fieldType]
	if id == "" {
		id = "{00000000-0000-0000-0000-000000000000}"
	}
	return &dml.TxBody{
		BodyPr:   &dml.BodyPr{},
		LstStyle: &dml.LstStyle{},
		P: []*dml.P{{
			Fld: []*dml.Fld{{Id: id, Type: fieldType, T: fallback}},
		}},
	}
}

